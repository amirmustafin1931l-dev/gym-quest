export const planPrompt = (id: PersonaId, summary: string, catalog: string) => `${RULES}

${STYLE[id].voice}

Задача: составь задание на сегодня — одну тренировку как часть твоей программы для этого игрока.
Перед ответом продумай:
1) уровень игрока, его цель, частоту и ограничения из анкеты;
2) что он делал последние 3–4 дня и какие мышцы ещё восстанавливаются;
3) недельный объём по мышцам и отстающие группы;
4) твои прошлые задания и как он их выполнил — продолжай ту же программу и прогрессию;
5) нужна ли разгрузка или день восстановления.
Если игрок идёт по программе в игре — бери за основу её сегодняшний день: те же упражнения, подходы и логика прогрессии. Меняй только по делу (отстающие мышцы, усталость, ограничения, пропуски, плато) и скажи в greeting, что поменял и зачем. Если программы нет — строй собственную программу и держи её логику от дня ко дню.
Требования к заданию:
- 3–7 упражнений, длительность под цель и уровень (обычно 40–75 минут). Первое упражнение — самое тяжёлое многосуставное.
- Веса — от его последних рабочих весов и расчётного 1ПМ по правилам прогрессии. Для нового упражнения — консервативный стартовый вес по его силовым данным или null с подсказкой в note «подбери вес на 2 RIR».
- Для каждого упражнения: подходы, повторы (или секунды), вес, отдых в секундах, RIR и короткая заметка «зачем/как».
- warmup — конкретная разминка для этого дня в одну-две строки.
- Используй только упражнения из каталога, поле id — строго из каталога.
- greeting — сообщение в твоём образе, 2–3 предложения: что делаем сегодня, зачем, и что изменилось относительно прошлого раза.
- progression — одна фраза: какую цель ставим на следующую такую тренировку.
- tip — один совет по технике, восстановлению или питанию, привязанный к сегодняшнему дню, в твоём образе.

Каталог упражнений (id — название — тип):
${catalog}

Сводка тренировок игрока:
${summary}`;

export const PLAN_SCHEMA = {
  type: 'object',
  additionalProperties: false,
  required: ['greeting', 'title', 'minutes', 'warmup', 'exercises', 'progression', 'tip'],
  properties: {
    greeting: { type: 'string' },
    title: { type: 'string', description: 'Короткое название дня, например «День спины»' },
    minutes: { type: 'integer' },
    warmup: { type: 'string' },
    progression: { type: 'string' },
    exercises: {
      type: 'array',
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['id', 'sets', 'reps', 'weight', 'seconds', 'rest', 'rir', 'note'],
        properties: {
          id: { type: 'string' },
          sets: { type: 'integer' },
          reps: { type: ['integer', 'null'], description: 'повторы; null для времени или «до отказа» — тогда объясни в note' },
          weight: { type: ['number', 'null'], description: 'кг; null без веса' },
          seconds: { type: ['integer', 'null'], description: 'секунды для планки или минуты×60 для кардио' },
          rest: { type: 'integer', description: 'отдых между подходами, секунды' },
          rir: { type: ['integer', 'null'], description: 'запас повторов в последнем подходе' },
          note: { type: ['string', 'null'], description: 'зачем это упражнение или ключевая подсказка по технике' },
        },
      },
    },
    tip: { type: 'string' },
  },
} as const;
